import { Table, TableCell, TableHeader, TableRow } from '@tiptap/extension-table'
import type { JSONContent, NodeViewRenderer } from '@tiptap/core'
import { liftMarkdownBlockImages } from './block-images'

/** Only rectangular, single-paragraph tables with a uniform header/column
 * alignment can use GFM without losing document semantics. */
export function canUseGfmTable(
  node: JSONContent,
  needsHtml: (node: JSONContent) => boolean,
): boolean {
  const rows = node.content ?? [],
    header = rows[0]?.content ?? []
  if (!header.length) return false
  return rows.every(
    (row, rowIndex) =>
      row.content?.length === header.length &&
      row.content.every((cell, column) => {
        const paragraph = cell.content?.[0]
        return (
          cell.type === (rowIndex === 0 ? 'tableHeader' : 'tableCell') &&
          cell.attrs?.colspan === 1 &&
          cell.attrs?.rowspan === 1 &&
          cell.attrs?.colwidth === null &&
          cell.attrs?.align === header[column]?.attrs?.align &&
          cell.content?.length === 1 &&
          paragraph?.type === 'paragraph' &&
          !needsHtml(paragraph) &&
          !(paragraph.content ?? []).some(
            (child) =>
              child.type !== 'text' ||
              // The official GFM serializer collapses Unicode whitespace and uses
              // U+001F as an internal line separator; HTML retains these characters.
              /[^\S ]|\u001f|^ | $| {2,}/.test(child.text ?? ''),
          )
        )
      }),
  )
}

export function tableExtensions(
  needsHtml: (node: JSONContent) => boolean,
  html: (node: JSONContent) => string,
  conversion: boolean,
  nodeView?: NodeViewRenderer,
) {
  return [
    Table.extend({
      ...(nodeView ? { addNodeView: () => nodeView } : {}),
      parseMarkdown(token, helpers) {
        return liftMarkdownBlockImages(this.parent?.(token, helpers) ?? [])
      },
      // Colgroup and layout styles are generated by the live official TableView.
      // Serialized HTML carries only cell semantics, avoiding a second layout DTO.
      renderHTML: ({ HTMLAttributes }) => ['table', HTMLAttributes, ['tbody', 0]],
      renderMarkdown(node, helpers, context) {
        return canUseGfmTable(node, needsHtml)
          ? (this.parent?.(node, helpers, context) ?? '')
          : html(node)
      },
    }).configure({ resizable: false, cellMinWidth: 100, ...(conversion ? { View: null } : {}) }),
    TableRow.configure({}),
    TableHeader.configure({}),
    TableCell.configure({}),
  ]
}
