"""Build self-hosted Unicode WOFF2 slices from the pinned Maple Mono CN release.

Requires fonttools==4.60.1 and brotli==1.2.0. No runtime Python dependency.
"""
from collections import defaultdict
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path
import sys
from zipfile import ZipFile

from fontTools import subset
from fontTools.ttLib import TTFont

SOURCE_URL = 'https://github.com/subframe7536/maple-font/releases/download/v7.9/MapleMono-CN-unhinted.zip'
ARCHIVE_SHA256 = 'd41cb72721e99cfe4fbd1a7b0f182a013457de46aa612018f924dd024699d3b9'
REGULAR_SHA256 = '0fcc5139bfd5ab14ff989bb7dfd5236d0cafc10e60b9828569e6883613ab4085'
OUTPUT = Path(__file__).resolve().parents[2] / 'packages/components/src/tiptap/fonts/maple-mono-cn'


def unicode_ranges(codepoints):
    runs = []
    for point in sorted(codepoints):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ','.join(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}' for start, end in runs)


def main(archive_path):
    archive_bytes = Path(archive_path).read_bytes()
    if sha256(archive_bytes).hexdigest() != ARCHIVE_SHA256:
        raise ValueError('Archive does not match the pinned v7.9 source')
    with ZipFile(BytesIO(archive_bytes)) as archive:
        regular = archive.read('MapleMono-CN-Regular.ttf')
        license_bytes = archive.read('LICENSE.txt')
    if sha256(regular).hexdigest() != REGULAR_SHA256:
        raise ValueError('Regular face does not match the pinned v7.9 source')
    original = TTFont(BytesIO(regular), recalcTimestamp=False)
    original_cmap = original.getBestCmap()
    buckets = defaultdict(list)
    for point in sorted(original_cmap):
        buckets[point // 512].append(point)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / 'LICENSE.txt').write_bytes(license_bytes)
    faces, files, covered = [], [], set()
    for index, (bucket, points) in enumerate(sorted(buckets.items())):
        font = TTFont(BytesIO(regular), recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.name_legacy = True
        options.name_languages = ['*']
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        font.flavor = 'woff2'
        filename = f'regular-{bucket * 512:05x}.woff2'
        destination = OUTPUT / filename
        font.save(destination)
        check = TTFont(destination)
        cmap = check.getBestCmap()
        if set(cmap) != set(points):
            raise ValueError(f'Unicode coverage changed in {filename}')
        for point, glyph in cmap.items():
            if check['hmtx'].metrics[glyph] != original['hmtx'].metrics[original_cmap[point]]:
                raise ValueError(f'Glyph advance changed for U+{point:X}')
        check.close()
        font.close()
        covered.update(cmap)
        ranges = unicode_ranges(points)
        faces.append(f'''@font-face {{
  font-family: 'Maple Mono CN';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('./{filename}') format('woff2');
  unicode-range: {ranges};
}}''')
        data = destination.read_bytes()
        files.append({'file': filename, 'bytes': len(data), 'sha256': sha256(data).hexdigest(), 'unicodeRange': ranges})
        if index % 8 == 0:
            print(f'Built {index + 1}/{len(buckets)} slices', flush=True)
    if covered != set(original_cmap):
        raise ValueError('Combined font slices lost characters')
    (OUTPUT / 'font.scss').write_text('// Generated by scripts/assets/build-maple-mono-font.py.\n' + '\n\n'.join(faces) + '\n', encoding='utf-8')
    manifest = {'source': SOURCE_URL, 'archiveSha256': ARCHIVE_SHA256, 'regularSha256': REGULAR_SHA256, 'codepoints': len(covered), 'files': files}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    original.close()
    print(f'Preserved {len(covered)} codepoints in {len(files)} slices ({sum(item["bytes"] for item in files)} bytes)', flush=True)


if __name__ == '__main__':
    main(sys.argv[1])
