function parseMode(argumentsList) {
  const supported = new Set(["--write", "--check", "--self-test"])
  requireCondition(argumentsList.length === 1 && supported.has(argumentsList[0]), "usage: node skills/exui-usage/scripts/update.mjs (--write | --check | --self-test)")
  return argumentsList[0]
}

async function generateOutputs(packages) {
  const tokens = await loadTokenInventory(packages)
  const components = await loadComponentInventory(packages.components)
  const outputs = {
    "component-exports.md": renderComponentInventory(components),
    "token-paths.md": renderTokenInventory(tokens),
  }
  validateGeneratedOutputs(outputs, { tokens, components })
  return outputs
}

async function main() {
  const mode = parseMode(process.argv.slice(2))
  if (mode === "--self-test") {
    await runSelfTest()
    return
  }

  const packages = await loadPackageSelection()
  await validateHumanDocuments(skillRoot)
  buildPublicEntries()
  const outputs = await generateOutputs(packages)

  if (mode === "--check") {
    await checkGeneratedDirectory(outputs)
    process.stdout.write("exui-usage generated references are current\n")
    return
  }

  await replaceGeneratedDirectory(outputs)
  process.stdout.write("exui-usage generated references updated\n")
}

main().catch((error) => {
  process.stderr.write(`exui-usage update failed: ${error.message}\n`)
  process.exitCode = 1
})
