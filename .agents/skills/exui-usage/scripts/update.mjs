function validateGeneratedOutputs(outputs, expected) {
  requireCondition(Object.keys(outputs).sort().join("\n") === generatedFileNames.join("\n"), "generated output set is incomplete")
  requireCondition(outputs["token-paths.md"] === renderTokenInventory(expected.tokens), "Token renderer is not deterministic")
  requireCondition(outputs["component-exports.md"] === renderComponentInventory(expected.components), "component renderer is not deterministic")
  for (const [name, content] of Object.entries(outputs)) {
    requireCondition(content.startsWith(generatedNotice), `${name}: generated notice is missing`)
    requireCondition(!content.includes("\r"), `${name}: generated output must use LF line endings`)
    requireCondition(content.endsWith("\n"), `${name}: generated output must end with a newline`)
  }
}

async function validateGeneratedDirectory(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const names = entries.filter((entry) => entry.isFile()).map((entry) => entry.name).sort()
  requireCondition(entries.every((entry) => entry.isFile()), `${path.basename(directory)} contains an unexpected directory`)
  requireCondition(names.join("\n") === generatedFileNames.join("\n"), `${path.basename(directory)} does not contain the complete generated file set`)
  for (const name of names) {
    const content = await readFile(path.join(directory, name), "utf8")
    requireCondition(content.startsWith(generatedNotice), `${name}: generated notice is missing`)
    requireCondition(!content.includes("\r") && content.endsWith("\n"), `${name}: generated file format is invalid`)
    const inventoryLines = content.split("\n").filter((line) => line.startsWith("- `"))
    requireCondition(inventoryLines.length > 0, `${name}: generated inventory is empty`)
    if (name === "token-paths.md") {
      for (const prefix of ["exuiTokens.", "componentRecipes.", "--"]) {
        requireCondition(inventoryLines.some((line) => line.startsWith(`- \`${prefix}`)), `${name}: ${prefix} inventory is missing`)
      }
      requireCondition(inventoryLines.every((line) => /^- `(?:exuiTokens\.|componentRecipes\.|--)[^`]+`$/.test(line)), `${name}: generated Token line is invalid`)
    } else {
      requireCondition(inventoryLines.every((line) => /^- `[^`]+` — (?:value|type|value \+ type)$/.test(line)), `${name}: generated component line is invalid`)
    }
  }
}

async function recoverInterruptedWrite(referenceDirectory = referencesRoot, operations = { rename }) {
  const target = path.join(referenceDirectory, "generated")
  const backup = path.join(referenceDirectory, ".generated-backup")
  const entries = await readdir(referenceDirectory, { withFileTypes: true })
  const temporaryEntries = entries.filter((entry) => entry.name.startsWith(".generated-tmp-"))
  requireCondition(temporaryEntries.length === 0, "unfinished generated temporary directory requires manual inspection")

  if (!await pathExists(backup)) {
    return
  }
  requireCondition(!await pathExists(target), "generated directory and backup both exist; refusing to guess which is current")
  await validateGeneratedDirectory(backup)
  await operations.rename(backup, target)
}

async function replaceGeneratedDirectory(outputs, referenceDirectory = referencesRoot, operations = { rename, rm }) {
  const target = path.join(referenceDirectory, "generated")
  const backup = path.join(referenceDirectory, ".generated-backup")
  await recoverInterruptedWrite(referenceDirectory, operations)
  const temporary = await mkdtemp(path.join(referenceDirectory, ".generated-tmp-"))
  let hadOriginal = false
  let originalMoved = false
  let replacementInstalled = false

  try {
    for (const name of generatedFileNames) {
      await writeFile(path.join(temporary, name), outputs[name], "utf8")
    }
    await validateGeneratedDirectory(temporary)

    hadOriginal = await pathExists(target)
    if (hadOriginal) {
      await operations.rename(target, backup)
      originalMoved = true
    }
    await operations.rename(temporary, target)
    replacementInstalled = true
    await validateGeneratedDirectory(target)
  } catch (error) {
    if (replacementInstalled && await pathExists(target)) {
      await operations.rm(target, { recursive: true, force: true })
    }
    if (originalMoved && await pathExists(backup)) {
      await operations.rename(backup, target)
    }
    if (await pathExists(temporary)) {
      await operations.rm(temporary, { recursive: true, force: true })
    }
    throw error
  }

  if (hadOriginal) {
    await operations.rm(backup, { recursive: true, force: true })
  }
}

async function checkGeneratedDirectory(outputs, directory = generatedRoot) {
  const changed = []
  for (const name of generatedFileNames) {
    const existing = await readFile(path.join(directory, name), "utf8").catch(() => null)
    if (existing !== outputs[name]) {
      changed.push(name)
    }
  }
  const extra = await readdir(directory, { withFileTypes: true }).catch(() => [])
  for (const entry of extra) {
    if (!generatedFileNames.includes(entry.name)) {
      changed.push(entry.name)
    }
  }
  requireCondition(changed.length === 0, `generated references are stale: ${sortUnique(changed).join(", ")}`)
}

async function expectRejection(action, expectedMessage) {
  let rejected = false
  try {
    await action()
  } catch (error) {
    rejected = true
    requireCondition(error.message.includes(expectedMessage), `expected failure containing ${expectedMessage}, received: ${error.message}`)
  }
  requireCondition(rejected, `expected rejection containing ${expectedMessage}`)
}

