function fail(message) {
  throw new Error(message)
}

function requireCondition(condition, message) {
  if (!condition) {
    fail(message)
  }
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, "\n")
}

function sortUnique(values) {
  return [...new Set(values)].sort((left, right) => left.localeCompare(right, "en"))
}

function isWithin(base, candidate) {
  const relative = path.relative(base, candidate)
  return relative === "" || (!relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative))
}

function requireWithin(base, candidate, label) {
  requireCondition(isWithin(base, candidate), `${label} resolves outside the allowed directory`)
}

function getExportTarget(manifest, exportName, condition) {
  const exported = manifest.exports?.[exportName]
  if (typeof exported === "string") {
    return exported
  }
  if (exported && typeof exported === "object" && typeof exported[condition] === "string") {
    return exported[condition]
  }
  if (
    exported &&
    typeof exported === "object" &&
    exported[condition] &&
    typeof exported[condition] === "object" &&
    typeof exported[condition].default === "string"
  ) {
    return exported[condition].default
  }
  fail(`${manifest.name}: export ${exportName} does not expose ${condition}`)
}

function validateExportTarget(packageDirectory, target, label) {
  const resolved = path.resolve(packageDirectory, target)
  requireWithin(packageDirectory, resolved, label)
  return target
}

async function readJson(filePath) {
  try {
    return JSON.parse(await readFile(filePath, "utf8"))
  } catch (error) {
    fail(`${path.basename(filePath)} is not readable JSON: ${error.message}`)
  }
}

async function pathExists(candidate) {
  try {
    await access(candidate)
    return true
  } catch {
    return false
  }
}

async function validatePackageSelection(root, selection) {
  requireCondition(selection && typeof selection === "object", "package selection must be an object")
  requireCondition(Array.isArray(selection.packages), "package selection must contain a packages array")
  requireCondition(selection.packages.length === 2, "package selection must contain exactly two packages")

  const roles = selection.packages.map((entry) => entry?.role)
  requireCondition(new Set(roles).size === roles.length, "package selection roles must be unique")
  requireCondition(roles.includes("tokens") && roles.includes("components"), "package selection must contain tokens and components roles")

  const canonicalRoot = await realpath(root)
  const result = {}

  for (const role of ["tokens", "components"]) {
    const entry = selection.packages.find((candidate) => candidate.role === role)
    const approved = approvedPackages[role]
    requireCondition(entry.workspace === approved.workspace, `${role}: unapproved workspace ${String(entry.workspace)}`)
    requireCondition(entry.name === approved.name, `${role}: package name must be ${approved.name}`)

    const unresolvedDirectory = path.resolve(canonicalRoot, entry.workspace)
    requireWithin(canonicalRoot, unresolvedDirectory, `${role} workspace`)
    const packageDirectory = await realpath(unresolvedDirectory).catch(() => fail(`${role}: workspace does not exist`))
    requireWithin(canonicalRoot, packageDirectory, `${role} workspace`)

    const manifestPath = path.join(packageDirectory, "package.json")
    const manifest = await readJson(manifestPath)
    requireCondition(manifest.name === entry.name, `${role}: package manifest name does not match selection`)

    if (role === "tokens") {
      // The tokens workspace is the internal build location; its artifacts
      // ship through the public components package subpath.
      requireCondition(manifest.private === true, "tokens: the internal tokens workspace must stay private")
    } else {
      requireCondition(manifest.private !== true, "components: private packages cannot be selected")
      requireCondition(manifest.exports && manifest.exports["."], "components: package root export is missing")
      validateExportTarget(packageDirectory, getExportTarget(manifest, ".", "types"), "components root export")
      const tokensEntry = approved.tokensEntry
      requireCondition(
        entry.tokensEntry === tokensEntry,
        `components: tokens entry must be ${tokensEntry}`
      )
      validateExportTarget(packageDirectory, getExportTarget(manifest, tokensEntry, "import"), "components tokens import export")
      validateExportTarget(packageDirectory, getExportTarget(manifest, tokensEntry, "require"), "components tokens require export")
      validateExportTarget(packageDirectory, getExportTarget(manifest, `${tokensEntry}/style.css`, "default"), "components tokens style export")
      validateExportTarget(packageDirectory, getExportTarget(manifest, `${tokensEntry}/font.css`, "default"), "components tokens font export")
    }

    result[role] = { directory: packageDirectory, manifest }
  }

  return result
}

async function loadPackageSelection(root = repositoryRoot, filePath = selectionFile) {
  return validatePackageSelection(root, await readJson(filePath))
}

function runPnpm(args, stage) {
  // Node cannot spawn a .cmd shim with shell disabled on Windows. Run the
  // Corepack pnpm entry with the current Node executable to preserve the
  // argument-array and no-shell boundary required by this updater.
  const isWindows = process.platform === "win32"
  const executable = isWindows ? process.execPath : "pnpm"
  const pnpmArguments = isWindows
    ? [path.join(path.dirname(process.execPath), "node_modules", "corepack", "dist", "pnpm.js"), ...args]
    : args
  const result = spawnSync(executable, pnpmArguments, {
    cwd: repositoryRoot,
    shell: false,
    stdio: "inherit",
  })

  if (result.error) {
    fail(`${stage}: unable to run pnpm: ${result.error.message}`)
  }
  if (result.status !== 0) {
    fail(`${stage}: pnpm exited with status ${String(result.status)}`)
  }
}

